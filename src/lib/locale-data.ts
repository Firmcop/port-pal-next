export function getTimezones(): string[] {
  // @ts-ignore — supportedValuesOf is broadly available in modern engines
  const fromIntl: string[] | undefined = typeof Intl !== "undefined" && (Intl as any).supportedValuesOf
    ? (Intl as any).supportedValuesOf("timeZone")
    : undefined;
  if (fromIntl && fromIntl.length) return fromIntl;
  // Fallback: a curated subset
  return Array.from(new Set(COUNTRIES.map((c) => c.timezone))).sort();
}
